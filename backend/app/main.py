"""
The backend application.

Run it with:  uvicorn app.main:app --reload --port 8000
  /api/...    REST API used by the website
  /admin      admin panel
  /media/...  uploaded files
  /docs       interactive API documentation (generated by FastAPI)
"""

from contextlib import asynccontextmanager

from fastapi import FastAPI
from fastapi.responses import RedirectResponse
from fastapi.staticfiles import StaticFiles
from sqlalchemy import select

from . import models as m
from .admin import setup_admin
from .api import content, forms
from .config import BASE_DIR, MEDIA_DIR
from .database import Base, SessionLocal, engine


def create_tables() -> None:
    """Create any missing tables, and the single rows of the three settings pages."""
    Base.metadata.create_all(engine)
    with SessionLocal() as db:
        for model in (m.SiteSettings, m.HomePage, m.AboutPage):
            if db.scalar(select(model).limit(1)) is None:
                db.add(model())
        db.commit()


@asynccontextmanager
async def lifespan(_app: FastAPI):
    create_tables()
    yield


app = FastAPI(title="AL-FOROB AVLODIDAN API", version="1.0", lifespan=lifespan)

# forms must be registered before the catch-all /api/{collection} routes
app.include_router(forms.router)
app.include_router(content.router)

MEDIA_DIR.mkdir(parents=True, exist_ok=True)
app.mount("/media", StaticFiles(directory=MEDIA_DIR), name="media")
app.mount("/static", StaticFiles(directory=BASE_DIR / "app" / "static"), name="static")

setup_admin(app)


@app.get("/", include_in_schema=False)
def root():
    return RedirectResponse("/admin")
